def main():
    ap = argparse.ArgumentParser(description="Genera il blog STRATIA")
    ap.add_argument("--future", action="store_true", help="include articoli con data futura")
    ap.add_argument("--drafts", action="store_true", help="include le bozze")
    ap.add_argument("--posts", default=str(ROOT / "blog" / "posts"), help="cartella degli articoli")
    ap.add_argument("--out", default=str(ROOT), help="cartella di uscita (default: radice del sito)")
    a = ap.parse_args()

    out_root = Path(a.out)
    blog_dir = out_root / "blog"
    authors = json.loads((ROOT / "blog" / "authors.json").read_text(encoding="utf-8"))

    posts, skipped = [], []
    today = dt.date.today()
    for f in sorted(Path(a.posts).glob("*.md")):
        try:
            p = Post(f, authors)
        except ValueError as e:
            sys.exit(f"ERRORE: {e}")
        if p.draft and not a.drafts:
            skipped.append((f.name, "bozza")); continue
        if p.date > today and not a.future:
            skipped.append((f.name, f"programmato per il {data_it(p.date)}")); continue
        posts.append(p)
    posts.sort(key=lambda p: p.date, reverse=True)
    slugs = [p.slug for p in posts]
    if len(slugs) != len(set(slugs)):
        sys.exit("ERRORE: due articoli hanno lo stesso indirizzo (slug)")

    blog_dir.mkdir(parents=True, exist_ok=True)
    # rimuove le pagine generate in precedenza che non servono piu'
    for d in blog_dir.iterdir():
        idx = d / "index.html"
        if d.is_dir() and d.name not in slugs and idx.exists() and GENERATED_MARK in idx.read_text(encoding="utf-8")[:300]:
            idx.unlink(); d.rmdir()

    (blog_dir / "index.html").write_text(page_index(posts), encoding="utf-8")
    for p in posts:
        d = blog_dir / p.slug
        d.mkdir(parents=True, exist_ok=True)
        (d / "index.html").write_text(page_post(p, posts), encoding="utf-8")
    (blog_dir / "feed.xml").write_text(feed(posts), encoding="utf-8")
    old_privacy = out_root / "privacy-blog.html"      # pagina di una versione precedente (non piu' usata)
    if old_privacy.exists() and GENERATED_MARK in old_privacy.read_text(encoding="utf-8")[:300]:
        old_privacy.unlink()
    (out_root / "sitemap.xml").write_text(sitemap(posts), encoding="utf-8")

    print(f"Articoli pubblicati: {len(posts)}")
    for p in posts:
        print(f"  {p.date}  /{p.url_path}  ({p.minutes} min)")
    for n, why in skipped:
        print(f"  non pubblicato: {n} ({why})")


if __name__ == "__main__":
    main()
