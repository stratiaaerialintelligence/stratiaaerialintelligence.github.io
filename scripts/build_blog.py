def esc(s):
    return html.escape(str(s if s is not None else ""), quote=True)


def data_it(d):
    return f"{d.day} {MESI[d.month - 1]} {d.year}"


def slugify(s):
    s = s.lower()
    for a, b in (("à", "a"), ("è", "e"), ("é", "e"), ("ì", "i"), ("ò", "o"), ("ù", "u")):
        s = s.replace(a, b)
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s


def parse_front_matter(text, path):
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n(.*)$", text, re.S)
    if not m:
        raise ValueError(f"{path.name}: manca il blocco iniziale tra '---'")
    meta = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            raise ValueError(f"{path.name}: riga non valida nell'intestazione: {line!r}")
        k, v = line.split(":", 1)
        k, v = k.strip(), v.strip()
        if v.startswith("[") and v.endswith("]"):
            v = [x.strip().strip('"\'') for x in v[1:-1].split(",") if x.strip()]
        else:
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                v = v[1:-1]
            if v.lower() in ("true", "false"):
                v = v.lower() == "true"
        meta[k] = v
    return meta, m.group(2).strip()


class Post:
    def __init__(self, path, authors):
        meta, body = parse_front_matter(path.read_text(encoding="utf-8"), path)
        for req in ("title", "date", "author"):
            if req not in meta:
                raise ValueError(f"{path.name}: campo obbligatorio mancante: {req}")
        self.path = path
        self.title = str(meta["title"])
        self.date = dt.date.fromisoformat(str(meta["date"]))
        self.author_id = str(meta["author"])
        if self.author_id not in authors:
            raise ValueError(f"{path.name}: autore sconosciuto '{self.author_id}' (vedi blog/authors.json)")
        self.author = authors[self.author_id]
        self.tags = meta.get("tags", []) or []
        if isinstance(self.tags, str):
            self.tags = [self.tags]
        self.series = meta.get("series", "")
        self.episode = meta.get("episode", "")
        self.image = meta.get("image", "images/blog/salerno-lungomare.jpg")
        self.image_alt = meta.get("image_alt", "")
        self.image_credit = meta.get("image_credit", "")
        self.linkedin = str(meta.get("linkedin_url", "") or "")
        self.instagram = str(meta.get("instagram_url", "") or "")
        self.draft = bool(meta.get("draft", False))
        stem = re.sub(r"^\d{4}-\d{2}-\d{2}-", "", path.stem)
        self.slug = slugify(meta.get("slug", stem))
        self.body_md = body
        self.body_html = md.markdown(body, extensions=["extra", "sane_lists"])
        self.body_html = self._decorate(self.body_html)
        words = len(re.findall(r"\w+", re.sub(r"<[^>]+>", " ", self.body_html)))
        self.minutes = max(1, round(words / 200))
        plain = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", self.body_html)).strip()
        self.excerpt = str(meta.get("excerpt") or (plain[:200].rsplit(" ", 1)[0] + "…"))
        self.url_path = f"blog/{self.slug}/"
        self.url = f"{BASE_URL}/{self.url_path}"

    @staticmethod
    def _decorate(h):
        # link esterni in nuova scheda, immagini con caricamento differito
        def ext(m):
            tag = m.group(0)
            if 'href="http' in tag and BASE_URL not in tag:
                if "target=" not in tag:
                    tag = tag[:-1] + ' target="_blank" rel="noopener">'
            return tag
        h = re.sub(r"<a [^>]*>", ext, h)
        h = h.replace("<img ", '<img loading="lazy" ')
        return h

    @property
    def badge(self):
        return self.series or (self.tags[0] if self.tags else "Blog")

    def og_image(self):
        og = ROOT / re.sub(r"\.jpg$", "-og.jpg", self.image)
        rel = re.sub(r"\.jpg$", "-og.jpg", self.image) if og.exists() else self.image
        return f"{BASE_URL}/{rel}"


